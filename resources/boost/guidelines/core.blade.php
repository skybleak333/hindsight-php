# Hindsight agent memory

- This application gives agents long-term memory with `fedoseev/hindsight-php`, a client for the Hindsight memory server.
- Activate the `hindsight-php-agent-memory` skill whenever you add memory to a Laravel AI SDK agent, store or recall memories, or write tests for code that talks to Hindsight.
